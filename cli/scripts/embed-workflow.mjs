// Embeds the canonical workflow YAML into a TS module so `wd install` can ship
// it inside dist/ — package.json `files` is ["dist"], so a sibling .yml would
// not survive `npm install -g`.
//
// JSON.stringify, not a template literal: the YAML is full of `${{ … }}`, which
// a JS template literal reads as a substitution. It would either throw at parse
// time or silently interpolate nothing, producing a workflow that installs
// cleanly and never matches a job id.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const yml = join(here, '..', '..', '.github', 'workflows', 'wd-assignment.yml');
const out = join(here, '..', 'src', 'workflow.generated.ts');

const body = readFileSync(yml, 'utf8');
writeFileSync(
  out,
  '// GENERATED by scripts/embed-workflow.mjs — do not edit.\n' +
    '// Source: .github/workflows/wd-assignment.yml\n' +
    `export const WORKFLOW_YAML = ${JSON.stringify(body)};\n`,
);
console.error(`embedded ${body.length} bytes of workflow YAML`);
